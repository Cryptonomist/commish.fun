/* Render the game's midfield logo once, as a transparent pixel image, for
 * the landing page to display.
 *
 *   npx tsx scripts/build-midfield-logo.mjs
 *
 * THE HERO CARRIES THE SAME DRAWING AS THE GAME, not a vector version of it.
 * The first hero badge was an SVG disc with the Laces component inside, and
 * it was a lookalike: different alpha, different laces size, smooth edges next
 * to a game whose every other mark is a hard square. The owner asked for the
 * two to match, and the only way two drawings match is when there is one
 * drawing. So this calls `drawMidfieldLogo` — the exact function the arcade
 * and the attract loop call — through a shim that keeps an alpha channel,
 * and writes the result as a PNG data URI into src/data/midfield-logo.ts.
 * The hero scales that image up with image-rendering: pixelated, which is how
 * the canvases are scaled too.
 *
 * Alpha is kept rather than flattened onto turf because the hero's ground is
 * CSS: the logo composites over whatever mow band it lands on, exactly as the
 * canvas version composites over the field it is drawn on.
 *
 * Re-run whenever drawMidfieldLogo or drawLaces changes; the generated file
 * is committed so the site does not need a build step to have it.
 */
import { deflateSync } from "node:zlib";
import { writeFileSync } from "node:fs";
import { drawMidfieldLogo, LOGO_R } from "../src/lib/pixel.ts";

const SIZE = 2 * LOGO_R + 1;
const OUT = "src/data/midfield-logo.ts";

/** An RGBA surface with source-over compositing, straight alpha, floats. */
function surface(w, h) {
  const px = new Float32Array(w * h * 4); // r,g,b in 0..255, a in 0..1
  let fill = [0, 0, 0, 1];
  const parse = (css) => {
    const s = String(css).trim();
    const hex = /^#([0-9a-f]{6})$/i.exec(s);
    if (hex) {
      const n = parseInt(hex[1], 16);
      return [(n >> 16) & 255, (n >> 8) & 255, n & 255, 1];
    }
    const m = /^rgba?\(([^)]+)\)$/i.exec(s);
    if (!m) throw new Error(`cannot parse ${css}`);
    const p = m[1].split(",").map((v) => Number(v.trim()));
    return [p[0], p[1], p[2], p.length > 3 ? p[3] : 1];
  };
  const ctx = {
    set fillStyle(v) {
      fill = parse(v);
    },
    get fillStyle() {
      return "#000";
    },
    fillRect(x, y, rw, rh) {
      const a = fill[3];
      for (let j = Math.round(y); j < Math.round(y) + rh; j++) {
        for (let i = Math.round(x); i < Math.round(x) + rw; i++) {
          if (i < 0 || j < 0 || i >= w || j >= h) continue;
          const o = (j * w + i) * 4;
          const da = px[o + 3];
          const oa = a + da * (1 - a);
          if (oa === 0) continue;
          for (let c = 0; c < 3; c++) {
            px[o + c] = (fill[c] * a + px[o + c] * da * (1 - a)) / oa;
          }
          px[o + 3] = oa;
        }
      }
    },
  };
  return { ctx, px };
}

const crc32 = (() => {
  const t = new Int32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c;
  }
  return (b) => {
    let c = -1;
    for (const v of b) c = t[(c ^ v) & 255] ^ (c >>> 8);
    return (c ^ -1) >>> 0;
  };
})();
const chunk = (type, data) => {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, "ascii"), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([len, body, crc]);
};

/** Eight-bit RGBA PNG, one IDAT, filter 0 on every scanline. */
function png(px, w, h) {
  const stride = 1 + w * 4;
  const raw = Buffer.alloc(h * stride);
  for (let y = 0; y < h; y++) {
    const row = y * stride + 1;
    for (let x = 0; x < w; x++) {
      const s = (y * w + x) * 4;
      const d = row + x * 4;
      raw[d] = Math.round(px[s]);
      raw[d + 1] = Math.round(px[s + 1]);
      raw[d + 2] = Math.round(px[s + 2]);
      raw[d + 3] = Math.round(px[s + 3] * 255);
    }
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(w, 0);
  ihdr.writeUInt32BE(h, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 6; // colour type: truecolour with alpha
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", ihdr),
    chunk("IDAT", deflateSync(raw, { level: 9 })),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

const { ctx, px } = surface(SIZE, SIZE);
drawMidfieldLogo(ctx, LOGO_R, LOGO_R);
const data = png(px, SIZE, SIZE).toString("base64");

writeFileSync(
  OUT,
  `/* GENERATED by scripts/build-midfield-logo.mjs from drawMidfieldLogo in
 * src/lib/pixel.ts. Do not edit; re-run the script when the drawing changes.
 *
 * The midfield logo the game paints, as a ${SIZE}x${SIZE} transparent PNG,
 * so the landing page shows the same drawing rather than a lookalike. */

export const MIDFIELD_LOGO_SIZE = ${SIZE};

export const MIDFIELD_LOGO =
  "data:image/png;base64,${data}";
`,
);
console.log(`${OUT}: ${SIZE}x${SIZE}, ${data.length} base64 chars`);
